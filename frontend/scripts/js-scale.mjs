// Масштаб выпуска JS: инварианты и их вывод из измерений.
//
// ЧТО ЗДЕСЬ ЗАМЕНЕНО
//
// До Phase 19S масштаб сборки охранял один абсолютный потолок:
// `totalJsGzipCeiling = 400 КиБ` с сообщением «check for duplicated shared
// code». Заголовок самого гейта относил суммарный выпуск к группе
// «наблюдение с запасом» — величине про хостинг, а не про посетителя, — но
// реализация клала находку в тот же массив `issues`, который останавливает
// выпуск. Расхождение намерения и реализации ничего не значило, пока число
// оставалось далеко: 400 КиБ выбирались при десяти чанках рантайма и
// суммарных 111,3 КиБ.
//
// Phase 19S измерила девять реальных исторических сборок от 80 до 250
// калькуляторов на неизменном наборе зависимостей. Результат:
//
//   величина                80 V2      250 V2     наклон        R²
//   суммарный выпуск JS     194,3 КиБ  406,0 КиБ  1266 Б/калк.  0,99933
//   общий код               104,0      105,2      ~0            —
//   замыкание маршрута       88,9       89,4      3,1 Б/калк.   0,753
//   общий остров             28,11      28,22     0,7 Б/калк.   0,589
//   медиана своего чанка      1,13       1,18     0,24 Б/калк.  0,592
//   крупнейший свой чанк      1,76       1,94     1,4 Б/калк.   0,743
//   вездесущая масса         336 Б      219 Б    убывает       —
//
// Двигался ТОЛЬКО суммарный выпуск, и двигался он линейно по числу
// калькуляторов: R² = 0,99933. Прирост 225 → 250 калькуляторов на 100,0%
// пришёлся на новые изолированные чанки; все 225 прежних чанков и все общие
// чанки остались побайтово теми же. Ни одного байта общего кода не
// продублировано.
//
// То есть абсолютный потолок стал измерять численность продукта, а не
// дефект. Он срабатывал бы на 246-м калькуляторе, тогда как замыкание
// маршрута дошло бы до своего потолка на 2076-м, общий остров — на 2836-м,
// крупнейший чанк — на 4712-м.
//
// ЧТО ОХРАНЯЕТСЯ ВМЕСТО НЕГО
//
// Наклонный бюджет той же формы, что уже принята для подборки и раздела:
// постоянная часть плюс надбавка на калькулятор. Плюс два инструмента,
// которые ловят дублирование напрямую, а не по косвенному признаку суммы.
//
// Пороги выведены из измеренных распределений; проверка мутациями —
// в `tests/jsScaleGate.test.ts` и в отчёте Phase 19S.

/**
 * Потолок общего кода: всё, что не является собственным чанком калькулятора.
 *
 * Измерено 104,0 КиБ при 80 калькуляторах и 105,2 КиБ при 250 — рост 1,2 % на
 * утроении продукта. Потолок 120 КиБ даёт 14 % запаса и остаётся тем местом,
 * куда упрётся попытка перенести стоимость из чанков в общий код, чтобы
 * пролезть под надбавкой.
 */
export const JS_SHARED_GZIP_CEILING = 120 * 1024;

/**
 * Надбавка на один калькулятор.
 *
 * Измеренная средняя стоимость собственного чанка — 1,20 КиБ gzip, устойчивая
 * от 80 до 250 калькуляторов. Крупнейший чанк за всю историю — 1,94 КиБ.
 * Надбавка 2,00 КиБ выбрана выше крупнейшего когда-либо выпущенного чанка:
 * волна, целиком составленная из самых тяжёлых калькуляторов проекта, всё
 * равно проходит. При этом встраивание общего острова поднимает эту величину
 * до 29,2 КиБ, а дублирование общей локализации — до 14,4 КиБ; обе мутации
 * не проходят с многократным запасом.
 */
export const JS_PER_CALCULATOR_GZIP = 2 * 1024;

/**
 * Медиана собственного чанка. Измерено 1,13 → 1,18 КиБ на 80 → 250.
 * Порог 2,00 КиБ — 1,7 измеренного. Ловит раздувание типичного чанка,
 * которое надбавка на калькулятор способна размыть средним.
 */
export const JS_OWN_MEDIAN_GZIP = 2 * 1024;

/**
 * 95-й процентиль собственного чанка. Измерено 1,42 → 1,63 КиБ.
 * Порог 3,00 КиБ — 1,8 измеренного. Ловит утяжеление верхнего хвоста
 * раньше, чем оно упрётся в потолок одного чанка (8 КиБ, не менялся).
 */
export const JS_OWN_P95_GZIP = 3 * 1024;

/**
 * Вездесущая масса: сколько байт несёт КАЖДЫЙ калькулятор.
 *
 * Считается как суммарная длина нормализованных фрагментов, встречающихся
 * минимум в половине собственных чанков. Сегодня это ровно 219 байт: три
 * строки импорта, обёртка острова и два служебных литерала — механическая
 * цена того, что чанк является отдельным модулем.
 *
 * Это прямая мера того, что старое сообщение называло «duplicated shared
 * code». Измерения по девяти историческим сборкам: 336 Б при 80–135
 * калькуляторах, 219 Б от 160 и дальше — величина не растёт с продуктом, а
 * убывает. Добавление 50 честных изолированных чанков оставляет её ровно
 * 219 Б. Встраивание общего острова в каждый чанк даёт 87 317 Б,
 * дублирование общей локализации — 50 642 Б. Различение — четырёхсоткратное.
 *
 * Порог 512 байт: 1,52 исторического максимума (336 Б) и в 170 раз ниже
 * мутации. Такой порог ловит дублирование от ~180 байт на чанк — то есть
 * 44 КиБ впустую на нынешних 250 калькуляторах.
 */
export const JS_UBIQUITOUS_BYTES_PER_CHUNK = 512;

/**
 * Хостинг — теми ограничениями, которые действительно существуют.
 *
 * Прежний потолок ссылался на хостинг, но измерял сжатую сумму, которой
 * платформа не оперирует. Cloudflare Pages ограничивает ЧИСЛО файлов
 * (20 000 на тарифе Free, 100 000 на платных) и РАЗМЕР одного файла (25 МиБ).
 * Выпуск на 250 калькуляторах — 1171 файл и 419,6 КиБ в крупнейшем.
 */
export const JS_DEPLOY_FILE_CEILING = 20000;
export const JS_ASSET_BYTES_CEILING = 25 * 1024 * 1024;

/** Наклонный бюджет суммарного выпуска JS для данного числа калькуляторов. */
export function jsScaleBudget(
  calculators,
  base = JS_SHARED_GZIP_CEILING,
  perCalculator = JS_PER_CALCULATOR_GZIP,
) {
  return base + perCalculator * Math.max(0, calculators);
}

/**
 * Нормализованные фрагменты минифицированного чанка.
 *
 * Идентификаторы длиной до трёх символов заменяются на `_`: минификатор даёт
 * им произвольные имена, и без нормализации один и тот же встроенный код
 * выглядел бы разным в каждом чанке. Фрагменты короче двенадцати символов
 * отбрасываются — на такой длине совпадение ничего не доказывает.
 */
export function normalizedFragments(source) {
  const parts = [];
  let depth = 0;
  let current = '';
  let quote = null;
  let escaped = false;
  for (const ch of source) {
    current += ch;
    if (quote) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') { quote = ch; continue; }
    if (ch === '(' || ch === '[' || ch === '{') depth += 1;
    else if (ch === ')' || ch === ']' || ch === '}') depth -= 1;
    else if ((ch === ';' || ch === ',') && depth <= 1) { parts.push(current); current = ''; }
  }
  if (current) parts.push(current);
  return parts
    .map((part) => part.trim())
    .filter((part) => part.length >= 12)
    .map((part) => part.replace(/\b[A-Za-z_$][A-Za-z0-9_$]{0,2}\b/g, '_'));
}

/**
 * Масса кода, которую несёт минимум половина чанков.
 *
 * Порог «половина» намеренно мягкий: код, встроенный в каждый калькулятор,
 * попадает в него заведомо, а редкие совпадения между парой родственных
 * калькуляторов — нет. Именно поэтому мера не срабатывает на 50 честных
 * новых чанках и срабатывает четырёхсоткратно на встраивании общего кода.
 */
export function ubiquitousMass(sources) {
  if (sources.length === 0) return { bytes: 0, fragments: [] };
  const seen = new Map();
  for (const source of sources) {
    for (const fragment of new Set(normalizedFragments(source))) {
      seen.set(fragment, (seen.get(fragment) ?? 0) + 1);
    }
  }
  const threshold = Math.ceil(sources.length / 2);
  const fragments = [];
  let bytes = 0;
  for (const [fragment, count] of seen) {
    if (count < threshold) continue;
    bytes += Buffer.byteLength(fragment);
    fragments.push({ fragment, count, bytes: Buffer.byteLength(fragment) });
  }
  fragments.sort((a, b) => b.bytes - a.bytes);
  return { bytes, fragments };
}

/** Процентиль по возрастающему массиву; нужен для медианы и p95. */
export function percentile(sortedAscending, fraction) {
  if (sortedAscending.length === 0) return 0;
  const index = Math.round(fraction * (sortedAscending.length - 1));
  return sortedAscending[Math.min(sortedAscending.length - 1, Math.max(0, index))];
}

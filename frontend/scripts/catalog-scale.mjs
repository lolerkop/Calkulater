// Масштаб подборки: цель сертификации и модель страничного набора.
//
// ЗАКОН ИЗМЕНЁН Catalog Scale 4, и это записано прямо.
//
// Прежний закон измерял одну страницу, которая росла вместе с ассортиментом:
// «вырасти эту страницу ещё на 50 карточек и проверь потолок». Он был верен,
// пока подборка была одним документом, и упирался в арифметику: каркас 8,96 КиБ
// плюс около 63 Б gzip на карточку в худшей локали дают при 500 калькуляторах
// примерно 40 КиБ, а Phase 17S измерила, что даже 400 карточек — это 30,44 КиБ.
// Потолок в 30 КиБ при этом верен: он и есть точка пересмотра архитектуры.
//
// Подборка стала страничной, поэтому вес страницы больше НЕ зависит от
// численности каталога — от неё зависит ЧИСЛО страниц. Прежняя формулировка
// измеряла бы то, чего в архитектуре больше нет, и её замена не смягчение:
// новая проверка строит ВЕСЬ набор страниц на целевой численности и требует,
// чтобы ХУДШАЯ страница осталась под тем же потолком в 30 КиБ.

/** До скольких калькуляторов подборка сертифицирована архитектурно. */
export const CATALOG_CERTIFIED_TOTAL = 500;

/**
 * Задел вперёд от ТЕКУЩЕЙ численности.
 *
 * Нужен по той же причине, что и раньше: фиксированная цель однажды остаётся
 * позади, и проверка молча становится пустой ровно тогда, когда она нужнее
 * всего. Величина взята прежняя — 50: при страничной подборке лишние
 * калькуляторы добавляют СТРАНИЦЫ, а не байты в страницу, поэтому задел стоит
 * почти ничего и служит только защитой от вырождения проверки.
 */
export const CATALOG_SCALE_RESERVE = 50;

/** Потолок HTML маршрута подборки. Catalog Scale 4 его НЕ меняла. */
export const CATALOG_HTML_CEILING_GZIP = 30 * 1024;

/** Цель проверки: всегда не меньше сертифицированной и всегда дальше текущей. */
export function catalogScaleTarget(
  total,
  certified = CATALOG_CERTIFIED_TOTAL,
  reserve = CATALOG_SCALE_RESERVE,
) {
  return Math.max(certified, total + reserve);
}

/** Сколько страниц занимает подборка заданной численности. */
export function catalogPageCountFor(total, pageSize) {
  return Math.max(1, Math.ceil(total / pageSize));
}

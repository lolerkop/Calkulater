// Масштаб подборки: цель прогноза и её постоянные.
//
// Вынесено отдельным модулем, чтобы проверку цели можно было прогнать тестом,
// не запуская всю проверку бюджетов: та читает dist и в свежей копии репозитория
// просто не отработала бы.

/** До скольких калькуляторов подборка обязана дожить, не выйдя за потолок. */
export const CATALOG_SCALE_TARGET_CARDS = 300;

/**
 * Задел вперёд от ТЕКУЩЕГО числа карточек.
 *
 * Нужен потому, что фиксированная цель однажды остаётся позади. Ровно это и
 * случилось в Phase 16: при 200 в настройке против 203 на сайте помощник роста
 * возвращал null, строка прогноза исчезла из отчёта, и проверка стала пустой
 * в тот самый момент, когда предупреждение было нужнее всего.
 */
export const CATALOG_SCALE_LOOKAHEAD_CARDS = 50;

/** Потолок HTML подборки. Phase 17S его НЕ меняла. */
export const CATALOG_HTML_CEILING_GZIP = 30 * 1024;

/** Цель прогноза: всегда строго дальше текущего числа карточек. */
export function catalogScaleTarget(
  cards,
  target = CATALOG_SCALE_TARGET_CARDS,
  lookahead = CATALOG_SCALE_LOOKAHEAD_CARDS,
) {
  return Math.max(target, cards + lookahead);
}

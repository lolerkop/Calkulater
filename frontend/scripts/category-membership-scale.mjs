// Масштаб страницы раздела: цель прогноза и её постоянные.
//
// Вынесено отдельным модулем по тем же причинам, что и `catalog-scale.mjs`:
// цель должна проверяться тестом, не читающим dist.

/**
 * До скольких калькуляторов ОДИН раздел обязан дожить, не выйдя за
 * routeHtmlGzip. Своего потолка здесь НЕТ: проверяется тот же жёсткий 15 КиБ,
 * что и у любого обычного маршрута.
 */
export const CATEGORY_MEMBERSHIP_TARGET = 100;

/**
 * Задел вперёд от ТЕКУЩЕГО числа членов самого крупного раздела.
 *
 * Та же защита от вырождения, что и у подборки: фиксированная цель однажды
 * оказывается позади, прогноз молча перестаёт строиться, и проверка становится
 * пустой в тот момент, когда предупреждение нужнее всего.
 */
export const CATEGORY_MEMBERSHIP_LOOKAHEAD = 25;

/** Цель прогноза: всегда строго дальше текущего числа членов. */
export function categoryMembershipTarget(
  members,
  target = CATEGORY_MEMBERSHIP_TARGET,
  lookahead = CATEGORY_MEMBERSHIP_LOOKAHEAD,
) {
  return Math.max(target, members + lookahead);
}

/**
 * Сколько калькуляторов вправе перечислять ItemList раздела.
 *
 * Та же величина и та же причина, что у каталога: перечень повторял имя,
 * адрес и описание каждого члена вторым экземпляром и рос вместе с сайтом —
 * на подлинных текстах около 87 B gzip на члена в развёрнутой записи и около
 * 25 в плоской. Ссылки при этом на месте, все до одной: ограничение касается
 * только перечня в разметке.
 *
 * Живёт здесь, чтобы обе проверки — бюджетов и структурированных данных —
 * говорили об одном и том же числе. У страницы своё значение намеренно:
 * поднятая там величина обязана упереться в этот предел.
 */
export const CATEGORY_ITEM_LIST_MAX = 24;

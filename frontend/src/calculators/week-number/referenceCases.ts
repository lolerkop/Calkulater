// Значения выведены вручную по календарю, а не прогоном функции.
//
// 2026-01-01 — четверг: день года 1, день недели 4.
//   floor((1 − 4 + 10) / 7) = floor(7 / 7) = 1.
// 2026-08-18: 31+28+31+30+31+30+31 = 212, +18 = 230-й день. 2026 не високосный.
//   С 1 января прошло 229 дней, 229 mod 7 = 5, четверг + 5 = вторник → день недели 2.
//   floor((230 − 2 + 10) / 7) = floor(238 / 7) = 34.
// 2024-02-29: 31 + 29 = 60-й день, год високосный.
// 2024-12-31 — вторник, 366-й день. Формула даёт 53, но 2024 начинается
//   с понедельника и содержит 52 недели, поэтому дата принадлежит первой
//   неделе 2025 года: неделя Пн 30.12.2024 — Вс 05.01.2025 содержит
//   четверг 2 января 2025.
// 2023-01-01 — воскресенье, день года 1, день недели 7.
//   floor((1 − 7 + 10) / 7) = floor(4 / 7) = 0 → дата принадлежит последней
//   неделе 2022 года. 2022 начинается с субботы и содержит 52 недели.

import type { CalculatorReferenceCase } from '../../lib/platform/types';

// Только объём в объём: перевод «стакан муки → граммы» требует плотности
// продукта, то есть отдельного датасета, и в этот конвертер не входит.
//
// Единицы разных стран не совпадают, поэтому каждая названа явно, а не выбрана
// молча по контексту. Значения выведены из точных определений:
//   жидкая унция США = 29,5735295625 мл (точно)
//   чайная ложка США = 1/6 жидкой унции · столовая = 1/2 · стакан = 8 унций
//   метрические ложки и стакан определены круглыми числами: 5, 15 и 250 мл
export const cookingVolumeReferenceCases: readonly CalculatorReferenceCase[] = [
  {
    name: 'стакан США равен 236,5882 миллилитра',
    inputs: { value: 1, from: 'cupUS', to: 'ml' },
    expectPrimary: '236,5882 мл',
  },
  {
    name: 'в стакане США шестнадцать столовых ложек США',
    inputs: { value: 1, from: 'cupUS', to: 'tbspUS' },
    expectPrimary: '16,0000 ст. л. (US)',
  },
  {
    name: 'метрический стакан — это ровно 250 миллилитров',
    inputs: { value: 1, from: 'cupM', to: 'ml' },
    expectPrimary: '250,0000 мл',
  },
  {
    name: 'обратно: литр — это четыре метрических стакана',
    inputs: { value: 1, from: 'l', to: 'cupM' },
    expectPrimary: '4,0000 стакан (метр.)',
  },
  {
    // Стаканы разных стран не совпадают — ровно поэтому они названы отдельно.
    name: 'стакан США меньше метрического',
    inputs: { value: 1, from: 'cupUS', to: 'cupM' },
    expectPrimary: '0,946353 стакан (метр.)',
  },
  {
    name: 'совпадение единиц не даёт дрейфа',
    inputs: { value: 36.6, from: 'ml', to: 'ml' },
    expectPrimary: '36,6000 мл',
  },
  {
    name: 'ноль остаётся нулём',
    inputs: { value: 0, from: 'cupUS', to: 'tspM' },
    expectPrimary: '0 ч. л. (метр.)',
  },
];

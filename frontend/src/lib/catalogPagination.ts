// Страничность подборки.
//
// Почему подборка вообще стала страничной. Одна плотная SSR-страница со всеми
// калькуляторами росла как O(численности): каркас 8,96 КиБ плюс около 63 Б
// gzip на карточку в худшей локали. При 500 калькуляторах это около 40 КиБ —
// потолок маршрута в 30 КиБ недостижим ни при какой чистке разметки, и Phase
// 17S уже измерила, что даже 400 карточек дают 30,44 КиБ. Убрать описания с
// карточек значило бы решить задачу за счёт продукта.
//
// Страничность меняет порядок роста: страница стоит O(размера страницы), а
// численность каталога влияет только на ЧИСЛО страниц. Поэтому потолок 30 КиБ
// остаётся прежним и перестаёт быть препятствием для роста ассортимента.
//
// Размер страницы выбран измерением, а не на глаз. Худшая локаль (uk),
// страница заполнена САМЫМИ ТЯЖЁЛЫМИ настоящими карточками:
//
//   N=100 -> 16,77 КиБ (запас 13,23)   страниц при 500: 5
//   N=150 -> 19,92 КиБ (запас 10,08)   страниц при 500: 4
//   N=200 -> 22,72 КиБ (запас  7,28)   страниц при 500: 3
//   N=250 -> 25,37 КиБ (запас  4,63)   страниц при 500: 2
//
// Взято 150: запас 10 КиБ означает, что средняя карточка может потяжелеть
// вдвое, прежде чем страница подойдёт к потолку, а при 500 калькуляторах
// выходит всего четыре страницы. У 100 запас больше, но выигрыш в безопасности
// уже не решающий (обе величины кратно перекрывают любой реальный рост), а
// страниц становится пять при 500 и восемь при 750.
export const CATALOG_PAGE_SIZE = 150;

/**
 * Сколько страниц занимает подборка. Пустая подборка всё равно даёт одну
 * страницу: у корня всегда есть адрес.
 */
export function catalogPageCount(total: number, pageSize = CATALOG_PAGE_SIZE): number {
  return Math.max(1, Math.ceil(total / pageSize));
}

/**
 * Срез страницы из ГЛОБАЛЬНО упорядоченного списка.
 *
 * Порядок задаётся один раз для всей подборки и режется по границам страниц:
 * сортировать внутри страницы отдельно нельзя, иначе страницы перестали бы
 * быть разбиением одной последовательности.
 */
export function catalogPageSlice<T>(items: readonly T[], page: number, pageSize = CATALOG_PAGE_SIZE): T[] {
  const start = (page - 1) * pageSize;
  return items.slice(start, start + pageSize);
}

/** Глобальная позиция первого элемента страницы, считая с единицы. */
export function catalogPageOffset(page: number, pageSize = CATALOG_PAGE_SIZE): number {
  return (page - 1) * pageSize;
}

/**
 * Адрес страницы подборки. Первая страница сохраняет канонический адрес
 * подборки: отдельного алиаса `page/1/` не существует.
 */
export function catalogPagePath(catalogPath: string, page: number): string {
  return page <= 1 ? catalogPath : `${catalogPath}page/${page}/`;
}

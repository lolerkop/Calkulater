// Согласование счётного слова с числом по восточнославянскому правилу: форма
// зависит только от двух последних цифр — 1 даёт первую форму, 2–4 вторую,
// остальное третью, а 11–19 всегда третью. Правило одинаково для русского и
// украинского, поэтому украинские наборы форм тоже проходят через эту функцию.
//
// Модуль отдельный от lib/format намеренно. Правило нужно и раннерам, и
// клиентскому слою локализации, а lib/clientI18n попадает в чанк, который
// грузят каталог и поиск. Импорт из lib/format утащил бы туда же Intl-обёртки
// и парсер чисел — полторы килобайты, которые этим страницам не нужны.

export function pluralRu(n: number, forms: [string, string, string]): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return forms[2];
  if (last > 1 && last < 5) return forms[1];
  if (last === 1) return forms[0];
  return forms[2];
}

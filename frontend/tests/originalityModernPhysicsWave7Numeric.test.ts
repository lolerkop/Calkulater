const BELOW = 'Ненулевое значение меньше числового диапазона';
const ABOVE = 'Значение выходит за числовой диапазон';
const displayed = (text: string): number => {
  const normalized = text.trim().replace(/[\u00a0\u202f]/g, '').replace(',', '.');
  const match = normalized.match(/^[+-]?\d+(?:\.\d+)?(?:·10\^[+-]?\d+)?/);
  expect(match, text).not.toBeNull(); return Number(match![0].replace('·10^', 'e'));
};
const assertQuantity = (value: string | number, decimal80: string, statistic = false) => {
  const text = String(value), expected = Number(decimal80);
  if (!Number.isFinite(expected)) { expect(text).toBe(ABOVE); return; }
  const mathematicallyNonzero = !/^[+-]?0(?:\.0*)?(?:e[+-]?\d+)?$/i.test(decimal80);
  if (expected === 0 && mathematicallyNonzero) { expect(text).toBe(BELOW); return; }
  const actual = displayed(text);
  expect(Number.isFinite(actual)).toBe(true);
  // Never let an absolute display tolerance hide a false zero.
  if (expected !== 0) expect(actual).not.toBe(0);
  if (expected === 0) { expect(actual).toBe(0); return; }
  const abs = Math.abs(expected);
  const tolerance = text.includes('·10^')
    ? Math.max(abs * 0.000501, Number.MIN_VALUE)
    : statistic ? 0.0000501 : abs >= 100 ? 0.00501 : abs >= 1 ? 0.000501 : abs >= .01 ? 0.0000501 : 0.000000501;
  expect(Math.abs(actual - expected), `${text} versus ${decimal80}`).toBeLessThanOrEqual(tolerance);
};
